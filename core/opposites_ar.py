def _parse(raw):
    out = []
    for line in raw.strip().splitlines():
        a, b = line.split("=")
        out.append((tuple(w.strip() for w in a.split("|")), tuple(w.strip() for w in b.split("|"))))
    return out


EASY, HARD = _parse(_EASY), _parse(_HARD)
