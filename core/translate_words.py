def _parse(raw):
    out = []
    for line in raw.strip().splitlines():
        en, ar = line.split("=")
        out.append((tuple(w.strip() for w in en.split("|")), tuple(w.strip() for w in ar.split("|"))))
    return out


EASY, HARD = _parse(_EASY), _parse(_HARD)
